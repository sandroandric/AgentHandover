use anyhow::Result;
use colored::Colorize;
use std::io::BufRead;
use std::path::{Path, PathBuf};

/// Written by the worker (`claude_skill_writer.EXPORT_MANIFEST`) in the data
/// dir: every path it exported into `~/.claude/skills`.
const EXPORT_MANIFEST: &str = "exported-skills.json";
/// The footer every generated Skill and command carries.
const GENERATED_MARKER: &str = "Generated by AgentHandover";

pub fn run(purge_data: bool) -> Result<()> {
    println!("{}", "AgentHandover Uninstaller".bold());
    println!();

    // Step 1: Stop services
    println!("Stopping services...");
    super::service::stop("all").ok();

    // Step 2: Remove launchd plists
    let home = std::env::var("HOME").unwrap_or_else(|_| "/tmp".to_string());
    let home = PathBuf::from(home);
    let launch_agents = home.join("Library/LaunchAgents");

    for label in &[
        "com.agenthandover.daemon.plist",
        "com.agenthandover.worker.plist",
    ] {
        let path = launch_agents.join(label);
        if path.exists() {
            std::fs::remove_file(&path)?;
            println!("  Removed {}", path.display());
        }
    }

    // Step 2b: Remove the opt-in zsh hook (`agenthandover setup --shell`)
    let zshrc = super::shell_hook::zshrc_path();
    if super::shell_hook::remove(&agenthandover_common::status::data_dir(), &zshrc)? {
        println!("  Removed the shell hook from {}", zshrc.display());
    }

    // Step 3: Remove native messaging host manifest from all supported browsers
    let manifest_name = "com.agenthandover.host.json";
    let mut nm_removed = false;
    for dir in crate::paths::native_messaging_hosts_dirs() {
        let nm_path = dir.join(manifest_name);
        if nm_path.exists() {
            std::fs::remove_file(&nm_path)?;
            println!("  Removed {}", nm_path.display());
            nm_removed = true;
        }
    }
    if !nm_removed {
        println!("  No native messaging host manifests found");
    }

    // Step 4: Remove PID files
    let data_dir = agenthandover_common::status::status_dir();
    for pid_file in &["daemon.pid", "worker.pid"] {
        let path = data_dir.join(pid_file);
        if path.exists() {
            std::fs::remove_file(&path)?;
        }
    }

    // Step 5: Remove status files
    for status_file in &["daemon-status.json", "worker-status.json"] {
        let path = data_dir.join(status_file);
        if path.exists() {
            std::fs::remove_file(&path)?;
        }
    }

    if purge_data {
        println!();
        println!("{}", "Purging user data...".yellow());
        // Collected before the data dir (which holds the export manifest)
        // is removed.
        let outside = purge_targets(&home, &data_dir, &knowledge_root(&home));
        if !outside.is_empty() {
            println!("AgentHandover also wrote these files outside its data directory:");
            for path in &outside {
                println!("  {}", path.display());
            }
            if confirm("Delete them too? [y/N] ") {
                for path in &outside {
                    remove_path(path)?;
                    println!("  Removed {}", path.display());
                }
            } else {
                println!("  Kept them.");
            }
        }
        if data_dir.exists() {
            std::fs::remove_dir_all(&data_dir)?;
            println!("  Removed {}", data_dir.display());
        }
    } else {
        println!();
        println!("User data preserved at: {}", data_dir.display());
        println!("To also remove data, run: agenthandover uninstall --purge-data");
    }

    println!();
    println!("{}", "Uninstall complete.".green().bold());
    println!(
        "You may also want to remove /usr/local/bin/agenthandover and /usr/local/bin/agenthandover-daemon"
    );
    Ok(())
}

/// `[knowledge] root_dir` from config.toml (default
/// `~/.agenthandover/knowledge`), with `~` expanded.
fn knowledge_root(home: &Path) -> PathBuf {
    let config = agenthandover_common::config::AppConfig::from_file(&super::config::config_path())
        .unwrap_or_default();
    expand_home(&config.knowledge.root_dir, home)
}

fn expand_home(path: &str, home: &Path) -> PathBuf {
    match path.strip_prefix("~/") {
        Some(rest) => home.join(rest),
        None if path == "~" => home.to_path_buf(),
        None => PathBuf::from(path),
    }
}

/// Everything AgentHandover wrote outside its data dir that exists now:
/// - the knowledge base (all of `~/.agenthandover` when the knowledge root
///   is inside it);
/// - `~/.claude/commands/agenthandover-list.md` and the generated
///   `ah-*.md` commands (a user's own `ah-*.md` has no generated footer and
///   is kept);
/// - the Skills recorded in the export manifest (never a glob, so the
///   user's own Skills survive), only paths inside `home`;
/// - `~/.hermes/skills/agenthandover/`.
pub(crate) fn purge_targets(home: &Path, data_dir: &Path, knowledge_root: &Path) -> Vec<PathBuf> {
    let mut targets: Vec<PathBuf> = Vec::new();
    let mut add = |path: PathBuf| {
        let exists = path.symlink_metadata().is_ok();
        let owned_elsewhere = path.starts_with(data_dir);
        let covered = targets.iter().any(|t| path.starts_with(t));
        if exists && !owned_elsewhere && !covered && path != home {
            targets.retain(|t| !t.starts_with(&path));
            targets.push(path);
        }
    };

    let product_home = home.join(".agenthandover");
    if knowledge_root.starts_with(&product_home) {
        add(product_home);
    } else {
        add(knowledge_root.to_path_buf());
    }

    let commands = home.join(".claude/commands");
    add(commands.join("agenthandover-list.md"));
    if let Ok(entries) = std::fs::read_dir(&commands) {
        let mut generated: Vec<PathBuf> = entries
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| {
                let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
                name.starts_with("ah-") && name.ends_with(".md") && is_generated(p)
            })
            .collect();
        generated.sort();
        generated.into_iter().for_each(&mut add);
    }

    for path in manifest_paths(&data_dir.join(EXPORT_MANIFEST)) {
        if path.is_absolute() && path.starts_with(home) && !path.components().any(|c| c.as_os_str() == "..") {
            add(path);
        }
    }

    add(home.join(".hermes/skills/agenthandover"));
    targets
}

fn is_generated(path: &Path) -> bool {
    std::fs::read_to_string(path)
        .map(|text| text.contains(GENERATED_MARKER))
        .unwrap_or(false)
}

/// The `paths` list of the export manifest; empty when missing or invalid.
fn manifest_paths(manifest: &Path) -> Vec<PathBuf> {
    let Ok(bytes) = std::fs::read(manifest) else {
        return Vec::new();
    };
    let Ok(value) = serde_json::from_slice::<serde_json::Value>(&bytes) else {
        return Vec::new();
    };
    value["paths"]
        .as_array()
        .map(|paths| {
            paths
                .iter()
                .filter_map(|p| p.as_str())
                .map(PathBuf::from)
                .collect()
        })
        .unwrap_or_default()
}

/// Remove a file, symlink or directory tree (a symlink itself, never its
/// target).
pub(crate) fn remove_path(path: &Path) -> std::io::Result<()> {
    match path.symlink_metadata() {
        Ok(meta) if meta.is_dir() => std::fs::remove_dir_all(path),
        Ok(_) => std::fs::remove_file(path),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(e),
    }
}

/// Ask once on stdin; anything but y/yes (or no answer) is no.
fn confirm(question: &str) -> bool {
    use std::io::Write;
    print!("{question}");
    std::io::stdout().flush().ok();
    let mut answer = String::new();
    if std::io::stdin().lock().read_line(&mut answer).is_err() {
        return false;
    }
    matches!(answer.trim().to_ascii_lowercase().as_str(), "y" | "yes")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(path: &Path, text: &str) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    /// J-privacy (#60) at unit level: one Skill exported to every target,
    /// a hand-written Skill and command next to them; the purge removes the
    /// product's files and nothing of the user's.
    #[test]
    fn purge_removes_the_products_files_and_keeps_the_users() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path().join("home");
        let data_dir = home.join("Library/Application Support/agenthandover");
        let knowledge = home.join(".agenthandover/knowledge");
        let generated = format!("---\nname: x\n---\n\n*{GENERATED_MARKER} v0.5*\n");

        write(&knowledge.join("procedures/file-expenses.json"), "{}");
        let skill = home.join(".claude/skills/file-expenses");
        write(&skill.join("SKILL.md"), &generated);
        let index = home.join(".claude/skills/AGENTHANDOVER-INDEX.md");
        write(&index, &generated);
        let mine = home.join(".claude/skills/mine/SKILL.md");
        write(&mine, "---\nname: mine\n---\nMy own skill\n");
        write(&home.join(".claude/commands/agenthandover-list.md"), &generated);
        write(&home.join(".claude/commands/ah-file-expenses.md"), &generated);
        let my_command = home.join(".claude/commands/ah-mine.md");
        write(&my_command, "my own command\n");
        let hermes = home.join(".hermes/skills/agenthandover");
        write(&hermes.join("file-expenses/SKILL.md"), &generated);
        let my_hermes = home.join(".hermes/skills/other/SKILL.md");
        write(&my_hermes, "x");
        write(
            &data_dir.join(EXPORT_MANIFEST),
            &serde_json::json!({"paths": [
                skill, index, "/etc/passwd", home.join("../outside"), data_dir.join("x")
            ]})
            .to_string(),
        );

        let targets = purge_targets(&home, &data_dir, &knowledge);
        let expected: Vec<PathBuf> = vec![
            home.join(".agenthandover"),
            home.join(".claude/commands/agenthandover-list.md"),
            home.join(".claude/commands/ah-file-expenses.md"),
            skill.clone(),
            index.clone(),
            hermes.clone(),
        ];
        assert_eq!(targets, expected);

        for path in &targets {
            remove_path(path).unwrap();
        }
        for path in &expected {
            assert!(!path.exists(), "{} should be gone", path.display());
        }
        assert!(mine.exists(), "a hand-written Skill survives");
        assert!(my_command.exists(), "a hand-written ah-*.md command survives");
        assert!(my_hermes.exists());
        assert!(data_dir.join(EXPORT_MANIFEST).exists(), "the data dir is purged separately");
    }

    #[test]
    fn custom_knowledge_root_and_nothing_to_remove() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path().join("home");
        let data_dir = home.join("data");
        let custom = home.join("Documents/kb");
        assert!(purge_targets(&home, &data_dir, &custom).is_empty());
        std::fs::create_dir_all(&custom).unwrap();
        assert_eq!(purge_targets(&home, &data_dir, &custom), vec![custom]);
    }

    #[test]
    fn tilde_expands_against_home() {
        let home = Path::new("/Users/me");
        assert_eq!(expand_home("~/.agenthandover/knowledge", home), home.join(".agenthandover/knowledge"));
        assert_eq!(expand_home("/opt/kb", home), PathBuf::from("/opt/kb"));
    }
}
