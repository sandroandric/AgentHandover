class TestSkillMdWriterSemanticSteps:
    """Generator-shaped steps (fields under ``parameters``) render fully."""

    def setup_method(self):
        self.tmpdir = tempfile.mkdtemp()
        self.writer = SkillMdWriter(workspace_dir=self.tmpdir)

    def _content(self, **overrides) -> str:
        return self.writer.write_sop(_make_v2_sop_template(**overrides)).read_text()

    def test_step_fields_rendered(self):
        content = self._content()
        assert (
            "2. [step_2] Run unit tests\n"
            "   App: VS Code → Terminal\n"
            "   Input: pytest tests/ -v\n"
            "   Verify: Output shows all tests passed\n"
        ) in content
        assert "   Target: ~/agenthandover/worker/main.py\n" in content

    def test_overview_sections(self):
        content = self._content()
        assert "## When to use\n\n- New feature branch is ready for staging" in content
        assert "- All CI jobs pass\n- staging health endpoint returns healthy" in content
        assert "## Common errors\n\n- CI fails on test job\n- Staging health returns old version" in content

    def test_sensitive_variable_is_a_credential_reference(self):
        variables = [{"name": "api_token", "type": "text", "sensitive": True,
                      "example": "sk-live-123"}]
        content = self._content(variables=variables)
        assert "- `api_token` (credential): take it from your credential store" in content
        assert "sk-live-123" not in content

    def test_routing_ignores_source_string(self):
        """The same steps render the same way whatever ``source`` says."""
        a = self._content(source="v2_focus_recording")
        b = self._content(source="passive_discovery")
        strip = lambda c: c.replace("Learned from: v2_focus_recording", "").replace(
            "Learned from: passive_discovery", "")
        assert strip(a) == strip(b)

    def test_legacy_string_variables(self):
        content = self._content(variables=["query", "region"])
        assert "- `query` (string, required)" in content
        assert "- `region` (string, required)" in content
