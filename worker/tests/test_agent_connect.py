def _stub_claude(tmp_path: Path, *, list_output: str, add_status: int = 0,
                 list_after_add: str | None = None) -> tuple[Path, Path]:
    """A ``claude`` stand-in that records its argv, one JSON list per line.

    ``mcp list`` prints *list_output* until an ``mcp add`` succeeded, then
    *list_after_add*.
    """
    log = tmp_path / "claude-argv.jsonl"
    state = tmp_path / "claude-added"
    after = list_output if list_after_add is None else list_after_add
    script = tmp_path / "claude"
    script.write_text(
        f"#!{sys.executable}\n"
        "import json, pathlib, sys\n"
        f"log = pathlib.Path({str(log)!r})\n"
        f"state = pathlib.Path({str(state)!r})\n"
        "with log.open('a') as fh:\n"
        "    fh.write(json.dumps(sys.argv[1:]) + '\\n')\n"
        "args = sys.argv[1:]\n"
        "if args[:2] == ['mcp', 'list']:\n"
        f"    print({after!r} if state.exists() else {list_output!r})\n"
        "elif args[:2] == ['mcp', 'add']:\n"
        f"    if {add_status} == 0:\n"
        "        state.touch()\n"
        "    else:\n"
        "        print('add failed: already exists', file=sys.stderr)\n"
        f"    sys.exit({add_status})\n",
        encoding="utf-8",
    )
    script.chmod(script.stat().st_mode | stat.S_IXUSR)
    return script, log


def _argv(log: Path) -> list[list[str]]:
    if not log.exists():
        return []
    return [json.loads(line) for line in log.read_text().splitlines()]


