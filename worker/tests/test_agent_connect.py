class TestConnectHermes:
    """Tests for Hermes integration.

    Hermes loads skills by walking ``~/.hermes/skills/`` and reading each
    subdirectory's ``SKILL.md`` file — NOT loose ``.md`` files.  These
    tests verify we write the correct layout:
    ``~/.hermes/skills/agenthandover/<slug>/SKILL.md``.
    """

    def test_writes_skill_in_hermes_layout(self, fake_kb: Path, tmp_path: Path, capsys):
        with patch("agenthandover_worker.agent_connect._get_kb_root", return_value=fake_kb / "knowledge"), \
             patch("agenthandover_worker.agent_connect.Path.home", return_value=tmp_path):
            connect_hermes()

        namespace_dir = tmp_path / ".hermes" / "skills" / "agenthandover"
        assert namespace_dir.is_dir()

        # Only the agent_ready procedure should be written, as a subdirectory
        # (beside the Commonplace note)
        slug_dirs = [
            d for d in namespace_dir.iterdir()
            if d.is_dir() and d.name != "agenthandover-commonplace"
        ]
        assert len(slug_dirs) == 1
        assert slug_dirs[0].name == "reddit-marketing"

        # The file must be named SKILL.md (Hermes convention)
        skill_file = slug_dirs[0] / "SKILL.md"
        assert skill_file.exists()

        content = skill_file.read_text(encoding="utf-8")
        # Frontmatter must include the name field for Hermes
        assert content.startswith("---\nname: reddit-marketing\ndescription: Keep the brand present in three subreddits every day.\n")
        assert "Max 5/day" in content
        assert "## Execution protocol" in content
        # Generator-shaped steps keep their target and verify line
        assert "1. [step_1] Open the Namecheap homepage\n" in content
        assert "   Target: https://www.namecheap.com\n" in content
        assert "   Verify: The Namecheap homepage loads" in content

        out = capsys.readouterr().out
        assert "Hermes integration ready" in out
        assert "Procedures installed: 1" in out

    def _connect(self, fake_kb: Path, home: Path, kb_root: Path | None = None) -> None:
        with patch("agenthandover_worker.agent_connect._get_kb_root",
                   return_value=kb_root or fake_kb / "knowledge"), \
             patch("agenthandover_worker.agent_connect.Path.home", return_value=home):
            connect_hermes()

    def test_records_what_it_wrote_in_a_manifest(self, fake_kb: Path, tmp_path: Path):
        self._connect(fake_kb, tmp_path)
        namespace_dir = tmp_path / ".hermes" / "skills" / "agenthandover"
        manifest = json.loads((namespace_dir / HERMES_MANIFEST).read_text())
        assert manifest["files"] == ["reddit-marketing/SKILL.md", HERMES_COMMONPLACE]

    def test_removes_only_what_its_manifest_lists(self, fake_kb: Path, tmp_path: Path):
        namespace_dir = tmp_path / ".hermes" / "skills" / "agenthandover"
        self._connect(fake_kb, tmp_path)
        # The user's own file inside the namespace, and in a generated dir.
        (namespace_dir / "my-notes").mkdir()
        (namespace_dir / "my-notes" / "SKILL.md").write_text("hand written", encoding="utf-8")
        (namespace_dir / "reddit-marketing" / "notes.txt").write_text("mine", encoding="utf-8")

        # The procedure is no longer agent_ready: its Skill goes, the rest stays.
        self._connect(fake_kb, tmp_path, kb_root=tmp_path / "empty-kb")

        assert not (namespace_dir / "reddit-marketing" / "SKILL.md").exists()
        assert (namespace_dir / "reddit-marketing" / "notes.txt").read_text() == "mine"
        assert (namespace_dir / "my-notes" / "SKILL.md").read_text() == "hand written"
        assert json.loads((namespace_dir / HERMES_MANIFEST).read_text())["files"] == [
            HERMES_COMMONPLACE,
        ]
        assert (namespace_dir / HERMES_COMMONPLACE).is_file()

    def test_an_upgrade_without_a_manifest_removes_only_generated_files(
        self, fake_kb: Path, tmp_path: Path,
    ):
        """Before the first manifest, only files carrying AgentHandover's
        footer (stale Skills of an older version) are taken as its own."""
        namespace_dir = tmp_path / ".hermes" / "skills" / "agenthandover"
        footer = "---\n*Generated by AgentHandover v0.4.0 (procedure schema 3.1.0)*\n"
        (namespace_dir / "old-workflow").mkdir(parents=True)
        (namespace_dir / "old-workflow" / "SKILL.md").write_text("old\n" + footer, encoding="utf-8")
        (namespace_dir / "mydailynews.md").write_text("flat layout\n" + footer, encoding="utf-8")
        (namespace_dir / "handmade").mkdir()
        (namespace_dir / "handmade" / "SKILL.md").write_text("mine", encoding="utf-8")
        (namespace_dir / "README.md").write_text("mine too", encoding="utf-8")

        self._connect(fake_kb, tmp_path)

        assert not (namespace_dir / "old-workflow").exists()
        assert not (namespace_dir / "mydailynews.md").exists()
        assert (namespace_dir / "handmade" / "SKILL.md").read_text() == "mine"
        assert (namespace_dir / "README.md").read_text() == "mine too"
        assert (namespace_dir / "reddit-marketing" / "SKILL.md").exists()

    def test_a_manifest_entry_outside_the_namespace_is_ignored(self, fake_kb: Path, tmp_path: Path):
        namespace_dir = tmp_path / ".hermes" / "skills" / "agenthandover"
        namespace_dir.mkdir(parents=True)
