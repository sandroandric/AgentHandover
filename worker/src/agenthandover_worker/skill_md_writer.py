"""SKILL.md Export Adapter — agent-readable markdown skill files.

Produces ``SKILL.<slug>.md`` files in a ``skills/`` directory, plus a
``SKILLS-INDEX.md`` manifest table.  Each file is rendered by
``skill_render.render_packet(proc, target="generic")``; SOP templates are
converted to procedures first, so both entry points produce the same
packet.

Implements the ``SOPExportAdapter`` ABC.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

import yaml

from agenthandover_worker import __version__
from agenthandover_worker.export_adapter import SOPExportAdapter
from agenthandover_worker.exporter import AtomicWriter
from agenthandover_worker.procedure_schema import sop_to_procedure
from agenthandover_worker.skill_render import slugify
from agenthandover_worker.skill_render import render_packet


class SkillMdWriter(SOPExportAdapter):
    """Write procedures as SKILL.<slug>.md files for AI agent consumption.

    Args:
        workspace_dir: Root directory under which ``skills/`` is created.
    """

    def __init__(self, workspace_dir: str | Path):
        self.workspace_dir = Path(workspace_dir).expanduser().resolve()
        self.skills_dir = self.workspace_dir / "skills"

    def _ensure_dirs(self) -> None:
        self.skills_dir.mkdir(parents=True, exist_ok=True)

    def write_sop(self, sop_template: dict) -> Path:
        """Write a single SKILL.<slug>.md file from an SOP template."""
        return self.write_procedure(sop_to_procedure(sop_template))

    def write_procedure(self, procedure: dict) -> Path:
        """Write a v3 procedure as ``skills/SKILL.<slug>.md``."""
        self._ensure_dirs()
        slug = slugify(procedure.get("id") or procedure.get("slug") or "unknown")
        path = self.skills_dir / f"SKILL.{slug}.md"
        AtomicWriter.write(path, render_packet(procedure, target="generic"))
        return path

    def write_all_sops(self, sop_templates: list[dict]) -> list[Path]:
        """Write all skill files + SKILLS-INDEX.md manifest."""
        paths = [self.write_sop(t) for t in sop_templates]

        if sop_templates:
            self._write_index(sop_templates)
        else:
            # Remove stale index when no SOPs to export
            index_path = self.skills_dir / "SKILLS-INDEX.md"
            if index_path.exists():
                index_path.unlink()

        return paths

    def write_metadata(self, metadata_type: str, data: dict) -> Path:
        """Write a metadata file (delegates to JSON in skills dir)."""
        import json

        self._ensure_dirs()
        filepath = self.skills_dir / f"{metadata_type}.json"
        enriched = {
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "metadata_type": metadata_type,
            **data,
        }
        AtomicWriter.write(filepath, json.dumps(enriched, indent=2, default=str))
        return filepath

    def get_sops_dir(self) -> Path:
        """Return the skills directory path."""
        return self.skills_dir

    def list_sops(self) -> list[dict]:
        """List existing skill files with summary info from their frontmatter."""
        sops = []
        if not self.skills_dir.exists():
            return sops

        for skill_file in sorted(self.skills_dir.glob("SKILL.*.md")):
            name = skill_file.stem  # e.g. "SKILL.file-expense-report"
            slug = name[6:] if name.startswith("SKILL.") else name

            fm: dict = {}
            try:
                text = skill_file.read_text(encoding="utf-8")
                end = text.find("\n---\n", 3)
                if text.startswith("---\n") and end != -1:
                    loaded = yaml.safe_load(text[4:end])
                    fm = loaded if isinstance(loaded, dict) else {}
            except (OSError, yaml.YAMLError):
                pass

            confidence = fm.get("confidence_score_avg")
            sops.append({
                "slug": slug,
                "title": fm.get("title") or slug.replace("-", " ").title(),
                "path": str(skill_file),
                "confidence": f"{confidence:.2f}" if isinstance(confidence, (int, float)) else "",
                "last_updated": datetime.fromtimestamp(
                    skill_file.stat().st_mtime, timezone.utc,
                ).strftime("%Y-%m-%d"),
                "size_bytes": skill_file.stat().st_size,
            })

        return sops

    def _write_index(self, sop_templates: list[dict]) -> Path:
        """Write SKILLS-INDEX.md — a table of all skills."""
        lines: list[str] = []
        lines.append("# Skills Index")
        lines.append("")
        lines.append(
            f"*Generated by AgentHandover v{__version__} on "
            f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}*"
        )
        lines.append("")
        lines.append("| Slug | Title | Confidence | Episodes | Last Updated |")
        lines.append("|------|-------|------------|----------|--------------|")

        for sop in sop_templates:
            slug = slugify(sop.get("slug", "unknown"))
            title = sop.get("title", "Untitled")
            confidence = sop.get("confidence_avg", 0.0)
            episodes = sop.get("episode_count", 0)
            updated = datetime.now(timezone.utc).strftime("%Y-%m-%d")
            link = f"[{slug}](SKILL.{slug}.md)"
            lines.append(
                f"| {link} | {title} | {confidence:.2f} | {episodes} | {updated} |"
            )

        lines.append("")

        index_path = self.skills_dir / "SKILLS-INDEX.md"
        AtomicWriter.write(index_path, "\n".join(lines))
        return index_path
