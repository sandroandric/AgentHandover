def _codex_block(ready: list[dict]) -> str:
    lines = [
        CODEX_BEGIN,
        "# Agent Instructions (AgentHandover)",
        "",
        "The following procedures were learned by observing the user's workflows.",
        "Each procedure includes steps, strategy, guardrails, and voice guidance.",
        "",
        "## Available Procedures",
        "",
    ]
    for proc in ready:
        lines.append(render_packet(proc, target="codex"))
    if not ready:
        lines.append("No agent-ready procedures yet. AgentHandover is still learning.")
        lines.append("")
    lines.append("*For real-time access, use the AgentHandover REST API at localhost:9477*")
    lines.append("*or the MCP server: `agenthandover-mcp`*")
    lines.append(CODEX_END)
    return "\n".join(lines) + "\n"


def connect_codex(target: Path | None = None, mode: str | None = None) -> int:
    """Write the AgentHandover block into ``AGENTS.md`` for Codex.

    The block sits between ``<!-- BEGIN agenthandover -->`` and ``<!-- END
    agenthandover -->``.  A missing file is created; an existing file with
    the markers gets only that span replaced.  An existing file without
    them is left alone: a preview is printed and 1 returned, unless *mode*
    is ``"append"`` (add the block at the end) or ``"force"`` (replace the
    whole file with the block).

    Args:
        target: The file; defaults to ``AGENTS.md`` in the current directory.
        mode: ``None``, ``"append"`` or ``"force"``.

    Returns:
        The exit status: 0 written, 1 refused.
    """
    from agenthandover_worker.exporter import AtomicWriter

    path = (target if target is not None else Path("AGENTS.md")).expanduser().resolve()
    ready = _ready_procedures()
    block = _codex_block(ready)
    print(f"Codex target: {path}")

    if not path.exists():
        AtomicWriter.write(path, block)
        action = "Created"
    else:
        text = path.read_text(encoding="utf-8")
        begin = text.find(CODEX_BEGIN)
        end = text.find(CODEX_END, begin + 1) if begin != -1 else -1
        if begin != -1 and end != -1:
            tail = text[end + len(CODEX_END):]
            AtomicWriter.write(path, text[:begin] + block.rstrip("\n") + tail)
            action = "Updated the AgentHandover block in"
        elif begin != -1 or CODEX_END in text:
            print(f"{path} has an unmatched AgentHandover marker; fix it by hand.")
            print(f"  The block must start with {CODEX_BEGIN} and end with {CODEX_END}.")
            return 1
        elif mode == "append":
            AtomicWriter.write(path, text.rstrip("\n") + "\n\n" + block)
            action = "Appended the AgentHandover block to"
        elif mode == "force":
            AtomicWriter.write(path, block)
            action = "Replaced"
        else:
            preview = block.splitlines()
            print(f"{path} already exists and has no AgentHandover block; not changed.")
            print("The block that would be added:")
            for line in preview[:12]:
                print(f"  | {line}")
            if len(preview) > 12:
                print(f"  | ... ({len(preview) - 12} more lines)")
            print("Rerun with --append to add it at the end of the file,")
            print("or with --force to replace the file with it.")
            return 1

    print(f"{action} {path}")
    print(f"  Procedures: {len(ready)}")
    return 0


