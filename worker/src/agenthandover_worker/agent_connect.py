def _connect_claude(args: argparse.Namespace) -> int:
    from agenthandover_worker.config import load_config

    connect_claude_code(skills_dir=load_config().export.skills_dir)
    print()
    return 0 if pair_claude_code() else 1


def main(argv: list[str] | None = None) -> None:
    """Entry point for `agenthandover connect` command."""
    parser = argparse.ArgumentParser(
        prog="agenthandover connect",
        description="Connect an AI agent to AgentHandover.",
        epilog=(
            "agents: claude-code (install Skills, register the MCP server), "
            "codex (AgentHandover block in AGENTS.md), openclaw (verify sync), "
            "hermes (install into ~/.hermes/skills/), mcp (show the MCP config)"
        ),
    )
    parser.add_argument("agent")
    parser.add_argument(
        "--path", type=Path, default=None,
        help="codex: the AGENTS.md to write (default: ./AGENTS.md)",
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        "--append", action="store_const", const="append", dest="mode",
        help="codex: add the block to an AGENTS.md that has none",
    )
    group.add_argument(
        "--force", action="store_const", const="force", dest="mode",
        help="codex: replace an AGENTS.md that has no block with the block",
    )
    args = parser.parse_args(argv)

    handlers = {
        "claude-code": _connect_claude,
        "claude": _connect_claude,
        "codex": lambda a: connect_codex(a.path, a.mode),
        "openclaw": lambda a: connect_openclaw() or 0,
        "claw": lambda a: connect_openclaw() or 0,
        "hermes": lambda a: connect_hermes() or 0,
        "mcp": lambda a: connect_mcp(),
    }
    agent = args.agent.lower().replace("_", "-")
    handler = handlers.get(agent)
    if handler is None:
        print(f"Unknown agent: {agent}")
        print(f"Available: {', '.join(handlers)}")
        sys.exit(1)
    sys.exit(handler(args))


if __name__ == "__main__":
    main()
