"""Agent connection helper — sets up integration between AgentHandover and execution agents.

Usage::

    agenthandover connect claude-code   # Install Skills and register the MCP server
    agenthandover connect codex         # Write the AgentHandover block into ./AGENTS.md
    agenthandover connect openclaw      # Verify OpenClaw path and sync
    agenthandover connect hermes        # Install skills into ~/.hermes/skills/
    agenthandover connect mcp           # Show MCP config for any agent
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from agenthandover_worker import paths
from agenthandover_worker.skill_render import description as skill_description
from agenthandover_worker.skill_render import render_packet, slugify, version_line

# Every file AgentHandover generates ends with ``version_line()``, which
# starts with this; a file without it was written by someone else.
GENERATED_MARKER = "Generated by AgentHandover"

# The name the MCP server is registered under in every agent.
MCP_SERVER_NAME = "agenthandover"

# Where the pkg installs the MCP server: the stable symlink first, then the
# venv entry point it points at.
_MCP_CANDIDATES = (
    "/usr/local/bin/agenthandover-mcp",
    "/usr/local/lib/agenthandover/venv/bin/agenthandover-mcp",
)

CODEX_BEGIN = "<!-- BEGIN agenthandover -->"
CODEX_END = "<!-- END agenthandover -->"

HERMES_MANIFEST = ".agenthandover-manifest.json"


def _get_kb_root() -> Path:
    """The knowledge base the worker writes (``paths.knowledge_base_dir()``)."""
    return paths.knowledge_base_dir()


def _load_procedures() -> list[dict]:
    """Load all procedures from the knowledge base."""
    kb_root = _get_kb_root()
    proc_dir = kb_root / "procedures"
    if not proc_dir.is_dir():
        return []

    procedures = []
    for f in sorted(proc_dir.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            procedures.append(data)
        except (json.JSONDecodeError, OSError):
            pass
    return procedures


def _ready_procedures() -> list[dict]:
    return [p for p in _load_procedures() if p.get("lifecycle_state") == "agent_ready"]


def _is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARKER in path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False


def mcp_command() -> str:
    """Absolute path of the ``agenthandover-mcp`` entry point agents launch.

    Agents start the server without the user's shell ``PATH``, so the
    registered command is absolute whenever it can be found: the pkg
    locations, then the entry point next to this interpreter, then
    ``PATH``.  The bare name is the last resort.
    """
    for candidate in _MCP_CANDIDATES:
        if os.access(candidate, os.X_OK):
            return candidate
    sibling = Path(sys.executable).parent / "agenthandover-mcp"
    if os.access(sibling, os.X_OK):
        return str(sibling)
    return shutil.which("agenthandover-mcp") or "agenthandover-mcp"


