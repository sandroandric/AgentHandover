def claude_binary() -> str | None:
    """The Claude Code CLI: ``$AH_CLAUDE_BIN``, else ``claude`` on ``PATH``,
    else its usual install locations.  ``None`` when it is not installed."""
    override = os.environ.get("AH_CLAUDE_BIN")
    if override:
        return override
    found = shutil.which("claude")
    if found:
        return found
    home = Path.home()
    for candidate in (
        home / ".claude" / "local" / "claude",
        home / ".local" / "bin" / "claude",
        Path("/opt/homebrew/bin/claude"),
        Path("/usr/local/bin/claude"),
    ):
        if os.access(candidate, os.X_OK):
            return str(candidate)
    return None


def _run_claude(claude: str, *args: str) -> subprocess.CompletedProcess | str:
    """Run the Claude Code CLI; an error string when it cannot be run."""
    try:
        return subprocess.run(
            [claude, *args], capture_output=True, text=True, timeout=120,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"could not run {claude}: {exc}"


def parse_claude_mcp_list(output: str) -> str:
    """State of our server in ``claude mcp list`` output.

    ``"connected"`` (health check passed), ``"failing"`` (registered, but
    the server did not start) or ``"absent"``.  A line looks like
    ``agenthandover: /usr/local/bin/agenthandover-mcp  - ✓ Connected``.
    """
    for line in output.splitlines():
        if line.strip().startswith(f"{MCP_SERVER_NAME}:"):
            status = line.rsplit(" - ", 1)[-1]
            if "Connected" in status and "Failed" not in status:
                return "connected"
            return "failing"
    return "absent"


def claude_mcp_state(claude: str) -> tuple[str, str]:
    """``(state, detail)`` from ``claude mcp list``; state as in
    :func:`parse_claude_mcp_list`, or ``"unknown"`` when the CLI failed."""
    result = _run_claude(claude, "mcp", "list")
    if isinstance(result, str):
        return "unknown", result
    if result.returncode != 0:
        return "unknown", (result.stderr or result.stdout).strip()
    return parse_claude_mcp_list(result.stdout), ""


def pair_claude_code(claude: str | None = None) -> bool:
    """Register the MCP server with Claude Code at user scope.

    Runs ``claude mcp add --scope user --transport stdio agenthandover --
    <agenthandover-mcp>`` (after removing a registration whose server does
    not start) and reports the state ``claude mcp list`` shows afterwards.
    Returns True when Claude Code reports the server as connected.
    """
    command = mcp_command()
    add_args = (
        "mcp", "add", "--scope", "user", "--transport", "stdio",
        MCP_SERVER_NAME, "--", command,
    )
    claude = claude or claude_binary()
    if claude is None:
        print("Claude Code CLI not found; the MCP server was not registered.")
        print("Install Claude Code, then run:")
        print(f"  claude {' '.join(add_args)}")
        return False

    state, detail = claude_mcp_state(claude)
    if state == "connected":
        print(f"MCP server already registered with Claude Code ({claude}): connected.")
        return True
    if state == "failing":
        _run_claude(claude, "mcp", "remove", "--scope", "user", MCP_SERVER_NAME)

    result = _run_claude(claude, *add_args)
    if isinstance(result, str) or result.returncode != 0:
        reason = result if isinstance(result, str) else (result.stderr or result.stdout).strip()
        print(f"Registering the MCP server with Claude Code failed: {reason}")
        return False

    state, detail = claude_mcp_state(claude)
    if state == "connected":
        print(f"MCP server registered with Claude Code: {command} (connected).")
        return True
    print(f"MCP server registered with Claude Code: {command}")
    if state == "failing":
        print("  but Claude Code could not start it. Run it by hand to see why:")
        print(f"  {command}")
    else:
        print(f"  but `claude mcp list` did not confirm it ({detail or state}).")
    return False


def prune_claude_skills(skills_dir: Path) -> list[str]:
    """Remove exported Skills whose procedure is not agent_ready.

    Only ``<skills_dir>/<slug>/SKILL.md`` directories that AgentHandover
    generated (the footer names it) and whose slug is a known procedure
    are removed, so a user's own Skills are never touched.  Returns the
    removed slugs.
    """
    from agenthandover_worker.claude_skill_writer import forget_export

    removed: list[str] = []
    for proc in _load_procedures():
        if proc.get("lifecycle_state") == "agent_ready":
            continue
        ident = proc.get("id") or proc.get("slug")
        if not ident:
            continue
        slug = slugify(ident)
        if _is_generated(skills_dir / slug / "SKILL.md"):
            shutil.rmtree(skills_dir / slug, ignore_errors=True)
            forget_export(skills_dir / slug)
            removed.append(slug)
    return removed


def connect_claude_code(
    commands_dir: Path | None = None,
    skills_dir: Path | None = None,
) -> None:
    """Make Claude Code see exactly the agent_ready procedures, as Skills.

    1. Writes each agent_ready procedure to ``<skills_dir>/<slug>/SKILL.md``
       (``ClaudeSkillWriter``, the ``claude-skill`` packet).
    2. Removes exported Skills of procedures that are not agent_ready.
    3. Writes ``<commands_dir>/agenthandover-list.md``, a pointer to those
       Skills, and removes the ``ah-<slug>.md`` commands older versions
       generated (a user's own ``ah-*.md`` files are kept).

    Does not register the MCP server; ``agenthandover connect
    claude-code`` does that with :func:`pair_claude_code`.

    Args:
        commands_dir: Defaults to ``~/.claude/commands``.
        skills_dir: Defaults to ``[export] claude_skills_dir``
            (``~/.claude/skills``).
    """
    from agenthandover_worker.claude_skill_writer import ClaudeSkillWriter
    from agenthandover_worker.config import load_config

    cmd_dir = commands_dir if commands_dir is not None else Path.home() / ".claude" / "commands"
    skills_root = skills_dir if skills_dir is not None else load_config().export.skills_dir

    ready = _ready_procedures()
    writer = ClaudeSkillWriter(skills_dir=skills_root)
    skill_paths = [writer.write_procedure(proc) for proc in ready]
    prune_claude_skills(skills_root)

    cmd_dir.mkdir(parents=True, exist_ok=True)
    for legacy in cmd_dir.glob("ah-*.md"):
        if _is_generated(legacy):
            legacy.unlink(missing_ok=True)

    index_lines = [
        "---",
        "description: List the AgentHandover Skills installed for Claude Code",
        "---",
        "",
        "# AgentHandover Skills",
        "",
        f"Each agent-ready Skill is installed in `{skills_root}`. "
        "Invoke one with `/<name>`, or describe the task and Claude Code "
        "picks the matching Skill.",
        "",
    ]
    if ready:
        for proc, path in zip(ready, skill_paths):
            index_lines.append(
                f"- **{proc.get('title', 'Untitled')}** (`/{path.parent.name}`): "
                f"{skill_description(proc)}"
            )
    else:
        index_lines.append("No agent-ready skills yet. AgentHandover is still learning your workflows.")
        index_lines.append("")
        index_lines.append("Record a Focus Session to teach it a workflow, then approve the draft.")
    index_lines += [
        "",
        "---",
        f"*{version_line()}. Run `agenthandover connect claude-code` to refresh.*",
    ]
    index_path = cmd_dir / "agenthandover-list.md"
    index_path.write_text("\n".join(index_lines), encoding="utf-8")

    print("Claude Code Skills ready.")
    print(f"  Skills directory: {skills_root}")
    print(f"  Skills installed: {len(ready)}")
    for path in skill_paths:
        print(f"    /{path.parent.name}  ({path})")
    print(f"  Index: {index_path}")


