def mcp_tools() -> list[tuple[str, list[str], str]]:
    """``(name, argument names, first docstring line)`` of every tool the
    MCP server exposes, read from :func:`mcp_server.build_mcp_server`."""
    import asyncio

    from agenthandover_worker.mcp_server import build_mcp_server

    tools = asyncio.run(build_mcp_server().list_tools())
    return [
        (
            tool.name,
            list((tool.inputSchema or {}).get("properties", {})),
            (tool.description or "").strip().splitlines()[0] if tool.description else "",
        )
        for tool in tools
    ]


def connect_mcp() -> int:
    """Print MCP configuration for any MCP-compatible agent."""
    try:
        tools = mcp_tools()
    except ImportError as exc:
        print(f"The MCP server cannot run: {exc}")
        return 1

    command = mcp_command()
    config = {"mcpServers": {MCP_SERVER_NAME: {"command": command}}}

    print("MCP Server configuration")
    print("========================")
    print()
    print("Claude Code (registers it at user scope):")
    print("  agenthandover connect claude-code")
    print("  # or: claude mcp add --scope user --transport stdio "
          f"{MCP_SERVER_NAME} -- {command}")
    print()
    print("Cursor / Windsurf / other MCP clients (mcpServers in their MCP settings):")
    print(json.dumps(config, indent=2))
    print()
    print("Available MCP tools:")
    width = max(len(f"{name}({', '.join(args)})") for name, args, _ in tools)
    for name, args, summary in tools:
        signature = f"{name}({', '.join(args)})"
        print(f"  - {signature.ljust(width)}  {summary}")
    print()
    print("Start the server manually:")
    print(f"  {command}        # stdio transport (for agents)")
    print(f"  {command} --sse  # SSE transport (for HTTP clients)")
    return 0


