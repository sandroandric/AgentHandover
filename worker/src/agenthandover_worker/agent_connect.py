def _hermes_previous_exports(namespace_dir: Path) -> set[str]:
    """Paths (relative to the namespace) the last export wrote.

    Read from the export manifest.  Before the first manifest exists,
    the files AgentHandover generated there (they carry its footer) are
    taken as its own, so an upgrade still cleans up stale Skills.
    """
    manifest = namespace_dir / HERMES_MANIFEST
    try:
        files = json.loads(manifest.read_text(encoding="utf-8")).get("files", [])
        return {f for f in files if isinstance(f, str)}
    except FileNotFoundError:
        pass
    except (OSError, ValueError, AttributeError):
        return set()
    if not namespace_dir.is_dir():
        return set()
    candidates = list(namespace_dir.glob("*/SKILL.md")) + list(namespace_dir.glob("*.md"))
    return {
        str(p.relative_to(namespace_dir)) for p in candidates if _is_generated(p)
    }


def connect_hermes() -> None:
    """Install AgentHandover skills into the Hermes skill library.

    Hermes (https://github.com/NousResearch/hermes-agent) loads skills
    by walking ``~/.hermes/skills/`` and reading each subdirectory's
    ``SKILL.md`` file (agentskills.io / anthropic-skills convention).
    The skill identity is taken from the ``name:`` frontmatter field
    (or the parent directory name as a fallback).

    Writes each agent-ready procedure to::

        ~/.hermes/skills/agenthandover/<slug>/SKILL.md

    and records the files written in ``.agenthandover-manifest.json``
    there.  A refresh deletes only files the previous manifest lists and
    this run did not write, so anything else in the namespace survives.
    Also prints the MCP config Hermes users can add for live semantic
    search and the execution-feedback loop.
    """
    from agenthandover_worker.exporter import AtomicWriter

    hermes_root = Path.home() / ".hermes"
    hermes_exists = hermes_root.is_dir()
    namespace_dir = hermes_root / "skills" / "agenthandover"
    previous = _hermes_previous_exports(namespace_dir)
    namespace_dir.mkdir(parents=True, exist_ok=True)

    ready = _ready_procedures()
    written: list[str] = []
    for proc in ready:
        rel = f"{slugify(proc.get('id') or proc.get('slug') or 'unknown')}/SKILL.md"
        AtomicWriter.write(namespace_dir / rel, render_packet(proc, target="hermes"))
        written.append(rel)

    root = namespace_dir.resolve()
    for rel in sorted(previous - set(written)):
        stale = (namespace_dir / rel).resolve()
        if root not in stale.parents or not stale.is_file():
            continue
        stale.unlink()
        if stale.parent != root:
            try:
                stale.parent.rmdir()  # only when nothing else is in it
            except OSError:
                pass

    AtomicWriter.write(
        namespace_dir / HERMES_MANIFEST,
        json.dumps({"generated_by": version_line(), "files": written}, indent=2) + "\n",
    )

    print("Hermes integration ready.")
    print(f"  Skills namespace: {namespace_dir}")
    print(f"  Procedures installed: {len(ready)}")
    print()
    if not hermes_exists:
        print("Note: ~/.hermes not found — Hermes may not be installed yet.")
        print("  Install Hermes: https://github.com/NousResearch/hermes-agent")
        print("  Skills have been staged — they'll be picked up once you install.")
        print()
    if ready:
        print("In Hermes, your skills are available via:")
        print("  /skills                    — list all skills")
        for proc, rel in zip(ready, written):
            print(f"  /{rel.split('/')[0]}   — {proc.get('title', '')}")
    else:
        print("No agent-ready skills yet. AgentHandover is still learning your workflows.")
        print("Record a Focus Session and approve the draft to make it available.")
    print()
    print("For live semantic search + execution feedback, also add the MCP server")
    print("to Hermes. Edit ~/.hermes/config.yaml and add:")
    print()
    print("  mcp:")
    print("    servers:")
    print(f"      {MCP_SERVER_NAME}:")
    print(f'        command: "{mcp_command()}"')
    print()
    print("Or run `agenthandover connect mcp` to see the JSON-format config.")


