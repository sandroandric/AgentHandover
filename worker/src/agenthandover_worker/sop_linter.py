"""SOP validation gate — lint/compile SOPs before export.

Validates SOP templates for structural correctness and completeness
before they are persisted or exported to disk.  Runs entirely in-memory
with no I/O or VLM calls.

Errors block export; warnings are logged but do not block.

Templates generated by the VLM from a recording (focus or passive) must
give every step a ``description`` and a ``verify`` line: the generation
prompts require both, so an answer without them is rejected (an error)
and goes back through regeneration.  Mechanically built templates (the
v1 focus fallback) keep these as warnings.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# Lint sources whose templates come from a VLM prompt that requires a
# per-step description and verify line: the labels main.py passes to
# ``lint_sop`` plus the generator's own ``source`` values.
VLM_GENERATED_SOURCES = frozenset({
    "v2_focus_recording",
    "v2_passive_discovery",
    "focus_v2",
    "passive",
    "retry_focus",
    "retry_passive",
})

# Matches {{var_name}} with optional whitespace inside braces.
_VAR_REF_RE = re.compile(r"\{\{\s*(\w+)\s*\}\}")


@dataclass
class LintIssue:
    """A single validation finding."""

    severity: str  # "error" or "warning"
    field: str  # which field has the issue
    message: str  # human-readable description


@dataclass
class LintResult:
    """Outcome of linting a single SOP template."""

    valid: bool  # True if no errors (warnings OK)
    issues: list[LintIssue] = field(default_factory=list)

    @property
    def errors(self) -> list[LintIssue]:
        return [i for i in self.issues if i.severity == "error"]

    @property
    def warnings(self) -> list[LintIssue]:
        return [i for i in self.issues if i.severity == "warning"]


def _collect_variable_refs(text: str) -> set[str]:
    """Extract all ``{{var_name}}`` references from *text*."""
    if not isinstance(text, str):
        return set()
    return set(_VAR_REF_RE.findall(text))


# The step fields a ``{{variable}}`` can appear in.  The internal template
# uses "step" for the action verb, the VLM's raw format and v3 procedures
# use "action"; the description is rendered to the agent as well.
STEP_TEXT_KEYS: tuple[str, ...] = (
    "step", "action", "description", "input", "location", "verify", "target",
)


def _step_text_fields(step: dict) -> list[str]:
    """Return the text values from step fields that may contain variable refs."""
    texts: list[str] = []
    for key in STEP_TEXT_KEYS:
        val = step.get(key)
        if isinstance(val, str):
            texts.append(val)
    # Parameters sub-dict may also contain refs.
    params = step.get("parameters")
    if isinstance(params, dict):
        for v in params.values():
            if isinstance(v, str):
                texts.append(v)
    return texts


def step_placeholders(steps: object) -> set[str]:
    """Every ``{{name}}`` referenced in the text fields of *steps*."""
    names: set[str] = set()
    for step in steps if isinstance(steps, list) else []:
        if isinstance(step, dict):
            for text in _step_text_fields(step):
                names.update(_collect_variable_refs(text))
    return names


def declared_variable_names(sop: dict) -> set[str]:
    """The variable names *sop* declares: ``variables`` on a template,
    ``inputs`` on a v3 procedure (dicts with a name, or bare names)."""
    declared: set[str] = set()
    for key in ("variables", "inputs"):
        items = sop.get(key)
        for var in items if isinstance(items, list) else []:
            name = var.get("name", "") if isinstance(var, dict) else var
            if isinstance(name, str) and name:
                declared.add(name)
    return declared


def _step_field(step: dict, key: str) -> str:
    """Return a step field from the top level or from ``parameters``."""
    val = step.get(key)
    if not val:
        params = step.get("parameters")
        if isinstance(params, dict):
            val = params.get(key)
    return val.strip() if isinstance(val, str) else ""


def lint_sop(sop_template: dict, source: str | None = None) -> LintResult:
    """Validate an SOP template before export.

    ``source`` names where the template came from.  For VLM-generated
    sources (``VLM_GENERATED_SOURCES``) a step without ``verify`` or
    ``description`` is an error; otherwise it is a warning.

    Returns a ``LintResult`` whose ``.valid`` flag is ``False`` when any
    error-severity issue is found (warnings alone do not block export).
    """
    issues: list[LintIssue] = []
    step_detail_severity = (
        "error" if source in VLM_GENERATED_SOURCES else "warning"
    )

    # ------------------------------------------------------------------
    # Errors (block export)
    # ------------------------------------------------------------------

    # 1. Missing or empty title
    if not sop_template.get("title"):
        issues.append(LintIssue("error", "title", "Missing or empty title"))

    # 2. Missing or empty identifier (``slug`` on a template, ``id`` on a
    #    v3 procedure)
    if not (sop_template.get("slug") or sop_template.get("id")):
        issues.append(LintIssue("error", "slug", "Missing or empty slug"))

    # 3. Missing or empty steps list
    steps = sop_template.get("steps")
    if not steps or not isinstance(steps, list):
        issues.append(LintIssue("error", "steps", "No steps defined"))
        steps = []

    # 4. Steps missing action field (internal="step", raw VLM="action")
    for idx, step in enumerate(steps):
        if not isinstance(step, dict):
            issues.append(
                LintIssue(
                    "error",
                    f"steps[{idx}]",
                    "Step is not a dict",
                )
            )
            continue
        action_value = step.get("step") or step.get("action")
        if not action_value:
            issues.append(
                LintIssue(
                    "error",
                    f"steps[{idx}].action",
                    "Step missing action",
                )
            )

    # 5. Variable references in steps not declared: an agent reading
    #    ``{{name}}`` has no declared input to fill it from.
    undeclared = step_placeholders(steps) - declared_variable_names(sop_template)
    for var_name in sorted(undeclared):
        issues.append(
            LintIssue(
                "error",
                f"variables.{var_name}",
                f"Variable '{{{{{var_name}}}}}' referenced in steps but not declared",
            )
        )

    # ------------------------------------------------------------------
    # Warnings (log but allow export)
    # ------------------------------------------------------------------

    # 1. Fewer than 2 steps
    if steps and len(steps) < 2:
        issues.append(
            LintIssue("warning", "steps", "SOP may be too simple (fewer than 2 steps)")
        )

    # 2. No task_description
    if not sop_template.get("task_description"):
        issues.append(
            LintIssue("warning", "task_description", "No task description")
        )

    # 3. Steps without verify or description (errors for VLM-generated
    #    sources, see ``step_detail_severity``)
    for idx, step in enumerate(steps):
        if not isinstance(step, dict):
            continue
        if not _step_field(step, "verify"):
            issues.append(
                LintIssue(
                    step_detail_severity,
                    f"steps[{idx}].verify",
                    "Step lacks verification",
                )
            )
        if not _step_field(step, "description"):
            issues.append(
                LintIssue(
                    step_detail_severity,
                    f"steps[{idx}].description",
                    "Step lacks description",
                )
            )

    # 4. Steps without app field
    for idx, step in enumerate(steps):
        if not isinstance(step, dict):
            continue
        has_app = bool(step.get("app"))
        params = step.get("parameters")
        if isinstance(params, dict) and params.get("app"):
            has_app = True
        if not has_app:
            issues.append(
                LintIssue(
                    "warning",
                    f"steps[{idx}].app",
                    "Step missing app context",
                )
            )

    # 5. Duplicate step actions
    action_texts: list[str] = []
    for step in steps:
        if not isinstance(step, dict):
            continue
        action_val = step.get("step") or step.get("action") or ""
        if action_val:
            action_texts.append(action_val)

    seen_actions: set[str] = set()
    for action_text in action_texts:
        if action_text in seen_actions:
            issues.append(
                LintIssue(
                    "warning",
                    "steps",
                    f"Duplicate step action: '{action_text}'",
                )
            )
            break  # Report once
        seen_actions.add(action_text)

    # 6. Low confidence
    confidence = sop_template.get("confidence_avg", sop_template.get("confidence", 1.0))
    if isinstance(confidence, (int, float)) and confidence < 0.5:
        issues.append(
            LintIssue(
                "warning",
                "confidence",
                f"Low confidence SOP ({confidence:.2f})",
            )
        )

    # 7. Unused variables (declared but never referenced)
    unused = declared_variable_names(sop_template) - step_placeholders(steps)
    for var_name in sorted(unused):
        issues.append(
            LintIssue(
                "warning",
                f"variables.{var_name}",
                f"Variable '{var_name}' declared but never referenced in steps",
            )
        )

    has_errors = any(i.severity == "error" for i in issues)
    return LintResult(valid=not has_errors, issues=issues)
